function toExerciseRecord(item: LearningExercise[] | Record<string, LearningExercise>): Record<string, LearningExercise> {
  if (Array.isArray(item)) {
    const res: Record<string, LearningExercise> = {};
    item.forEach((ex) => {
      res[ex.id] = ex;
    });
    return res;
  }
  return item;
}

